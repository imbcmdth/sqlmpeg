def test_scale_reports_expected_dimensions(tmp_path: Path) -> None:
    _require_fixture(_TESTSRC)
    out_path = tmp_path / "scaled.mp4"
    query = f"SELECT scale(a.frame, 0.5) FROM input('{_sql_path(_TESTSRC)}') a"

    _compile_and_run(query, out_path)

    stream = _ffprobe_video_stream(out_path)
    assert stream["width"] == _SRC_WIDTH // 2
    assert stream["height"] == _SRC_HEIGHT // 2


def test_trim_reports_expected_duration(tmp_path: Path) -> None:
    _require_fixture(_TESTSRC)
    out_path = tmp_path / "trimmed.mp4"
    query = (
        f"SELECT a.frame FROM input('{_sql_path(_TESTSRC)}') a "
        "WHERE a.t BETWEEN 0 AND 1"
    )

    _compile_and_run(query, out_path)

    duration = _ffprobe_duration(out_path)
    assert duration == pytest.approx(1.0, abs=0.2)


def test_hflip_matches_pil_flipped_source_by_phash(tmp_path: Path) -> None:
    _require_fixture(_TESTSRC)
    out_path = tmp_path / "hflipped.mp4"
    query = f"SELECT hflip(a.frame) FROM input('{_sql_path(_TESTSRC)}') a"

    _compile_and_run(query, out_path)

    source_png = tmp_path / "source_frame.png"
    output_png = tmp_path / "output_frame.png"
    _extract_frame(_TESTSRC, 1.0, source_png)
    _extract_frame(out_path, 1.0, output_png)

    with Image.open(source_png) as source_img:
        expected = source_img.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
        expected_hash = imagehash.phash(expected)
    with Image.open(output_png) as output_img:
        actual_hash = imagehash.phash(output_img)

    distance = expected_hash - actual_hash
    assert distance <= _PHASH_MAX_DISTANCE


