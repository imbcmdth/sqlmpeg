"""End-to-end exec tests: compile sqlmpeg queries and run them through real
ffmpeg against synthetic fixtures generated by ``scripts/gen_fixtures.py``.

Marked ``@pytest.mark.exec`` (registered in ``pyproject.toml``); excluded
from the default test run via ``addopts = -m "not exec"``. Run explicitly::

    python -m pytest -m exec tests/exec -q

Requires ``ffmpeg``/``ffprobe`` on PATH and the fixtures already generated
(``python scripts/gen_fixtures.py``). Tests skip cleanly if either is
missing, per plan 010.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import imagehash
import pytest
from PIL import Image

from sqlmpeg.compiler import compile_sql
from sqlmpeg.emit import build_ffmpeg_args, emit

pytestmark = pytest.mark.exec

_FIXTURES_DIR = Path(__file__).resolve().parent.parent / "fixtures"
_TESTSRC = _FIXTURES_DIR / "testsrc.mp4"
_AV2 = _FIXTURES_DIR / "av2.mp4"
_AV3 = _FIXTURES_DIR / "av3.mp4"

_SRC_WIDTH = 320
_SRC_HEIGHT = 240

_SUBPROCESS_TIMEOUT = 60.0
_PHASH_MAX_DISTANCE = 8


# ---------------------------------------------------------------------------
# skip / helper plumbing
# ---------------------------------------------------------------------------


def _require_fixture(path: Path) -> None:
    if not path.exists():
        pytest.skip(f"fixture missing: {path} (run scripts/gen_fixtures.py first)")


@pytest.fixture(autouse=True)
def _require_ffmpeg_tools() -> None:
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        pytest.skip("ffmpeg/ffprobe not found on PATH")


def _sql_path(path: Path) -> str:
    """Render `path` as the body of a SQL string literal.

    Forward slashes even on Windows: ffmpeg accepts them, and it sidesteps
    backslash-escaping inside the SQL string literal entirely.
    """
    return path.resolve().as_posix()


def _compile_and_run(query: str, out_path: Path) -> None:
    graph = compile_sql(query)
    emitted = emit(graph)
    args = build_ffmpeg_args(emitted, str(out_path))
    args.insert(1, "-y")
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT
    )
    assert result.returncode == 0, result.stderr
    assert out_path.exists()


def _ffprobe_video_stream(path: Path) -> dict[str, object]:
    args = [
        "ffprobe",
        "-v",
        "error",
        "-select_streams",
        "v:0",
        "-show_entries",
        "stream=width,height",
        "-of",
        "json",
        str(path),
    ]
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT
    )
    assert result.returncode == 0, result.stderr
    data = json.loads(result.stdout)
    streams = data["streams"]
    assert streams, f"no video stream found in {path}"
    stream: dict[str, object] = streams[0]
    return stream


def _ffprobe_duration(path: Path) -> float:
    args = [
        "ffprobe",
        "-v",
        "error",
        "-show_entries",
        "format=duration",
        "-of",
        "json",
        str(path),
    ]
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT
    )
    assert result.returncode == 0, result.stderr
    data = json.loads(result.stdout)
    return float(data["format"]["duration"])


def _ffprobe_streams(path: Path) -> list[dict[str, object]]:
    args = [
        "ffprobe",
        "-v",
        "error",
        "-show_entries",
        "stream=index,codec_type,codec_name",
        "-show_entries",
        "stream_tags=language",
        "-of",
        "json",
        str(path),
    ]
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT
    )
    assert result.returncode == 0, result.stderr
    data = json.loads(result.stdout)
    streams: list[dict[str, object]] = data["streams"]
    return streams


def _extract_frame(video: Path, t: float, out_png: Path) -> None:
    args = [
        "ffmpeg",
        "-y",
        "-ss",
        str(t),
        "-i",
        str(video),
        "-frames:v",
        "1",
        str(out_png),
    ]
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT
    )
    assert result.returncode == 0, result.stderr
    assert out_png.exists()


